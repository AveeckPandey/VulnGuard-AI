"""
VulnGuard AI - Assessment Schemas
Defines input payloads and comprehensive output responses for vulnerability investigations.
"""
import re
from typing import List, Optional
from pydantic import BaseModel, Field, field_validator
from backend.schemas.risk import AssetCriticality, InternetExposure, RiskScoreBreakdown
from backend.schemas.intelligence import AggregatedIntel

CVE_PATTERN = re.compile(r"CVE-[0-9]{4}-[0-9]{4,}")


class AssessmentRequest(BaseModel):
    cve_id: str = Field(..., description="CVE Identifier, e.g. CVE-2021-44228", examples=["CVE-2021-44228"])
    asset_criticality: AssetCriticality = Field(default=AssetCriticality.MEDIUM, description="Business criticality of the affected system")
    internet_exposure: InternetExposure = Field(default=InternetExposure.INTERNAL, description="Network perimeter exposure status")
    system_context: Optional[str] = Field(None, description="Optional analyst notes on deployment environment (e.g. Apache Log4j 2.14 on public edge gateway)")
    simulate_offline: bool = Field(False, description="Explicitly use simulated offline fixtures for testing/demos without network calls")

    @field_validator("cve_id")
    @classmethod
    def validate_and_normalize_cve_id(cls, v: str) -> str:
        clean = v.strip().upper()
        if not CVE_PATTERN.fullmatch(clean):
            raise ValueError(f"Invalid CVE ID format: '{v}'. Must match standard pattern 'CVE-YYYY-NNNN+' (e.g. CVE-2021-44228).")
        return clean


class AiRemediation(BaseModel):
    executive_summary: str = Field(..., description="High-level risk narrative for CISOs and security leads")
    technical_impact: str = Field(..., description="In-depth analysis of vulnerable attack vectors and mechanisms")
    exploitation_assessment: str = Field(..., description="Evaluation of in-the-wild exploitation risks based on EPSS and KEV")
    remediation_steps: List[str] = Field(..., description="Prioritized concrete steps to patch or eliminate the vulnerability")
    mitigation_workarounds: List[str] = Field(..., description="Temporary compensating controls if immediate patching is not possible")
    evidence_citations: List[str] = Field(..., description="Cited intelligence sources and reference URLs")
    model_used: str = Field(..., description="LLM model ID or 'deterministic-fallback-rules' if Bedrock was unavailable")
    is_fallback_deterministic: bool = Field(False, description="True if generated by offline rule engine rather than LLM")


class AssessmentResponse(BaseModel):
    id: str = Field(..., description="Unique assessment UUID")
    cve_id: str
    owner_user_id: Optional[str] = Field(None, description="Cognito user sub of the assessment owner")
    asset_criticality: AssetCriticality
    internet_exposure: InternetExposure
    system_context: Optional[str] = None
    intelligence: AggregatedIntel
    risk_score: RiskScoreBreakdown
    remediation: AiRemediation
    created_at: str
    execution_time_ms: float
    disclaimer: str = Field(
        default="VulnGuard AI risk score is a custom heuristic prioritization model. Always review critical findings against organizational policy.",
        description="Standard security disclaimer"
    )


class AssessmentSummary(BaseModel):
    id: str
    cve_id: str
    owner_user_id: Optional[str] = None
    priority_level: str
    total_score: float
    cvss_base_score: Optional[float]
    epss_probability: Optional[float]
    is_known_exploited: Optional[bool] = None
    asset_criticality: AssetCriticality
    internet_exposure: InternetExposure
    created_at: str


class PaginatedAssessmentsResponse(BaseModel):
    items: List[AssessmentSummary]
    count: int = Field(..., description="Number of items returned in the current page")
    next_cursor: Optional[str] = Field(None, description="Base64 encoded pagination key for retrieving subsequent results")
    has_more: bool = Field(False, description="Whether additional records exist beyond the current page")
